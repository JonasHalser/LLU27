-- Monthly supporter jokers. Repeatable; requires users, supporters and weekly_goals.
CREATE TABLE IF NOT EXISTS supporter_jokers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 supporter_id INT UNSIGNED NULL,
 runner_id INT UNSIGNED NOT NULL,
 joker_year SMALLINT UNSIGNED NOT NULL,
 joker_month TINYINT UNSIGNED NOT NULL,
 joker_type ENUM('weekly_boost','run_30h','next_run_150') NOT NULL,
 unit ENUM('km','minutes','hours','loops','meters') NOT NULL,
 baseline_value DECIMAL(12,2) UNSIGNED NOT NULL,
 target_value DECIMAL(12,2) UNSIGNED NOT NULL,
 iso_year SMALLINT UNSIGNED NULL,
 iso_week TINYINT UNSIGNED NULL,
 issued_at DATETIME NOT NULL,
 deadline_at DATETIME NULL,
 status ENUM('active','succeeded','failed') NOT NULL DEFAULT 'active',
 resolved_at DATETIME NULL,
 activity_id BIGINT UNSIGNED NULL,
 activity_distance_m DECIMAL(12,2) UNSIGNED NULL,
 penalty_points TINYINT UNSIGNED NOT NULL DEFAULT 3,
 UNIQUE KEY uniq_supporter_joker_month(supporter_id,joker_year,joker_month),
 INDEX idx_joker_runner_status(runner_id,status),
 INDEX idx_joker_deadline(status,deadline_at),
 FOREIGN KEY(supporter_id) REFERENCES supporters(id) ON DELETE SET NULL,
 FOREIGN KEY(runner_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT chk_supporter_joker_month CHECK(joker_month BETWEEN 1 AND 12),
 CONSTRAINT chk_supporter_joker_values CHECK(baseline_value>0 AND target_value>0),
 CONSTRAINT chk_supporter_joker_penalty CHECK(penalty_points=3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
